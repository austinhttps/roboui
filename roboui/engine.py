class LlamaCppInferenceEngine(BaseInferenceEngine):
    """Local GGUF quantized inference engine using llama-cpp-python."""

    def __init__(self, config: RoboUIConfig):
        super().__init__(config)
        self.model = None

        if not Path(config.model_path).exists():
            raise ModelFileNotFoundError(
                f"Model file not found at '{config.model_path}'. "
                f"Download GGUF weights or run in mock mode (ROBOUI_MOCK_MODE=true)."
            )

        self._initialize_model()

    def _handle_vram_failure(self, error: Exception) -> bool:
        """Handle CUDA/VRAM allocation failures by falling back to CPU."""
        logger.warning(
            "VRAM offload failed with %s. Falling back to CPU inference (n_gpu_layers=0).",
            error,
        )
        self.config.n_gpu_layers = 0
        return True

    def _initialize_model(self):
        """Lazy load llama-cpp model with error boundary for VRAM exhaustion."""
        try:
            import llama_cpp
            self.model = llama_cpp.Llama(
                model_path=self.config.model_path,
                n_gpu_layers=self.config.n_gpu_layers,
                n_ctx=self.config.max_context_tokens,
            )
        except (RuntimeError, MemoryError) as exc:
            if self.config.n_gpu_layers > 0:
                self._handle_vram_failure(exc)
                import llama_cpp
                self.model = llama_cpp.Llama(
                    model_path=self.config.model_path,
                    n_gpu_layers=0,
                    n_ctx=self.config.max_context_tokens,
                )
            else:
                raise

    def generate_ui(self, image_bytes: Optional[bytes] = None, custom_notes: str = "") -> GenerationResult:
        start_time = time.perf_counter()
        image_summary = f"[Binary image sketch: {len(image_bytes)} bytes]" if image_bytes else "[No image sketch]"
        prompt = f"Convert this UI layout to HTML/Tailwind: {image_summary} {custom_notes}"
        sanitized_prompt, redacted_pii = sanitize_pii(prompt)

        output = self.model(
            sanitized_prompt,
            max_tokens=self.config.max_context_tokens,
            stop=["```\n\n"],
        )
        text = output["choices"][0]["text"]
        extracted = extract_html(text)
        final_html = wrap_in_airgap_sandbox(extracted) if self.config.enforce_csp else extracted

        elapsed_ms = (time.perf_counter() - start_time) * 1000.0
        tokens_used = output.get("usage", {}).get("total_tokens", len(text) // 4)

        return GenerationResult(
            html_code=final_html,
            semantic_description=sanitized_prompt,
            redacted_pii=redacted_pii,
            tokens_used=tokens_used,
            latency_ms=elapsed_ms,
        )


def get_engine(config: RoboUIConfig) -> BaseInferenceEngine:
    """Factory creating the appropriate inference engine based on configuration."""
    if config.mock_mode:
        return MockInferenceEngine(config)
    return LlamaCppInferenceEngine(config)
