class GemmaVisionService(BaseInferenceEngine):
    """Multimodal vision inference service powered by quantized GGUF weights via llama-cpp-python."""

    def __init__(self, config: RoboUIConfig, fallback_to_mock: bool = False):
        super().__init__(config)
        self.fallback_to_mock = fallback_to_mock
        self.is_degraded = False
        self._mock_delegate: Optional[MockInferenceEngine] = None
        self.model = None

        if config.mock_mode:
            self._mock_delegate = MockInferenceEngine(config)
            return

        model_file = Path(config.model_path)
        if not model_file.exists():
            if fallback_to_mock:
                logger.warning(
                    "Local GGUF model not found at '%s'. Gracefully falling back to MockInferenceEngine.",
                    config.model_path,
                )
                self.is_degraded = True
                self._mock_delegate = MockInferenceEngine(config)
                return
            raise ModelFileNotFoundError(
                f"Model file not found at '{config.model_path}'. "
                f"Download GGUF weights or run in mock mode (ROBOUI_MOCK_MODE=true)."
            )

        self._initialize_llama_model()

    def _handle_vram_failure(self, error: Exception) -> bool:
        """Handle CUDA/VRAM allocation failures by falling back to CPU execution."""
        logger.warning(
            "VRAM offload failed with %s. Falling back to CPU inference (n_gpu_layers=0).",
            error,
        )
        self.config.n_gpu_layers = 0
        return True

    def _initialize_llama_model(self):
        """Load llama-cpp model with multimodal projection and VRAM fallback boundary."""
        try:
            import llama_cpp
            chat_handler = None
            if self.config.mmproj_path and Path(self.config.mmproj_path).exists():
                try:
                    from llama_cpp.llama_chat_format import Llava15ChatHandler
                    chat_handler = Llava15ChatHandler(clip_model_path=self.config.mmproj_path)
                    logger.info("Loaded multimodal projector from %s", self.config.mmproj_path)
                except Exception as proj_err:
                    logger.warning("Failed to initialize vision projector: %s", proj_err)

            self.model = llama_cpp.Llama(
                model_path=self.config.model_path,
                n_gpu_layers=self.config.n_gpu_layers,
                n_ctx=self.config.max_context_tokens,
                chat_handler=chat_handler,
            )
        except (RuntimeError, MemoryError) as exc:
            if self.config.n_gpu_layers > 0:
                self._handle_vram_failure(exc)
                import llama_cpp
                self.model = llama_cpp.Llama(
                    model_path=self.config.model_path,
                    n_gpu_layers=0,
                    n_ctx=self.config.max_context_tokens,
                )
            else:
                raise OutOfMemoryInferenceError(f"Insufficient memory to allocate model context: {exc}") from exc

    def generate_ui(self, image_bytes: Optional[bytes] = None, custom_notes: str = "") -> GenerationResult:
        """Execute multimodal UI generation with robust OOM handling."""
        if self._mock_delegate:
            return self._mock_delegate.generate_ui(image_bytes=image_bytes, custom_notes=custom_notes)

        start_time = time.perf_counter()

        try:
            system_prompt = (
                "You are an expert frontend developer. Your task is to output strictly valid HTML, "
                "Tailwind CSS, and vanilla JavaScript. Never output conversational filler, markdown "
                "formatting tags, or explanations. Only output code."
            )
            human_text = "Translate this hand-drawn UI sketch into a responsive website using Tailwind CSS."
            if custom_notes:
                human_text += f" Notes: {custom_notes}"
            sanitized_human_text, redacted_pii = sanitize_pii(human_text)

            # Multimodal payload formatting if image is provided
            if image_bytes and hasattr(self.model, "create_chat_completion"):
                mime = "image/jpeg" if (image_bytes.startswith(b"\xff\xd8") or b"JFIF" in image_bytes[:32]) else "image/png"
                b64_img = base64.b64encode(image_bytes).decode("utf-8")
                messages = [
                    {
                        "role": "system",
                        "content": system_prompt,
                    },
                    {
                        "role": "user",
                        "content": [
                            {"type": "text", "text": sanitized_human_text},
                            {"type": "image_url", "image_url": {"url": f"data:{mime};base64,{b64_img}"}},
                        ],
                    },
                ]
                output = self.model.create_chat_completion(
                    messages=messages,
                    max_tokens=self.config.max_context_tokens,
                )
                raw_text = output["choices"][0]["message"]["content"]
                tokens_used = output.get("usage", {}).get("total_tokens", len(raw_text) // 4)
            else:
                # Text-prompt fallback
                prompt = f"{system_prompt}\n\nHuman: {sanitized_human_text}"
                output = self.model(
                    prompt,
                    max_tokens=self.config.max_context_tokens,
                    stop=["```\n\n"],
                )
                raw_text = output["choices"][0]["text"]
                tokens_used = output.get("usage", {}).get("total_tokens", len(raw_text) // 4)

            # Route raw LLM output through markdown-stripping regex
            extracted = extract_html(raw_text)
            final_html = wrap_in_airgap_sandbox(extracted) if self.config.enforce_csp else extracted
            elapsed_ms = (time.perf_counter() - start_time) * 1000.0

            return GenerationResult(
                html_code=final_html,
                semantic_description=sanitized_human_text,
                redacted_pii=redacted_pii,
                tokens_used=tokens_used,
                latency_ms=elapsed_ms,
            )
        except (RuntimeError, MemoryError) as mem_err:
            logger.error("Out of Memory error encountered during generation: %s", mem_err)
            raise OutOfMemoryInferenceError(f"Generation aborted due to VRAM/RAM exhaustion: {mem_err}") from mem_err


# Alias for backward compatibility
LlamaCppInferenceEngine = GemmaVisionService


def get_engine(config: RoboUIConfig, fallback_to_mock: bool = False) -> BaseInferenceEngine:
    """Factory creating the appropriate inference engine based on configuration."""
    if config.mock_mode:
        return MockInferenceEngine(config)
    return GemmaVisionService(config, fallback_to_mock=fallback_to_mock)
