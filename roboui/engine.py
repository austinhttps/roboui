from roboui.sanitizer import sanitize_pii

logger = logging.getLogger("roboui.engine")


class ModelFileNotFoundError(FileNotFoundError):
    """Raised when the specified local GGUF model weights cannot be found on disk."""
    pass


@dataclass
class GenerationResult:
    """Encapsulates the end-to-end outcome of a UI generation cycle."""

    html_code: str
    semantic_description: str
    redacted_pii: List[str] = field(default_factory=list)
    tokens_used: int = 0
    latency_ms: float = 0.0

    @property
    def sanitized_pii_count(self) -> int:
        """Return the count of distinct PII items scrubbed."""
        return len(self.redacted_pii)


class BaseInferenceEngine(ABC):
    """Abstract base class for RoboUI inference engines."""

    def __init__(self, config: RoboUIConfig):
        self.config = config

    @abstractmethod
    def generate_ui(self, image_bytes: Optional[bytes] = None, custom_notes: str = "") -> GenerationResult:
        """Run the end-to-end pipeline: vision analysis, PII scrub, code synthesis, sandbox wrapping."""
        pass


